_COMPILED = [(p, re.compile(p.regex, re.IGNORECASE)) for p in PATTERNS]

_NORM_RE = re.compile(r"\s+")


def normalize_text(*parts: str | None) -> str:
    """Нормализация текста для матчинга: регистр, ё, лишние пробелы."""
    joined = " ".join(p for p in parts if p)
    joined = joined.replace("\xa0", " ").replace("ё", "е").replace("Ё", "Е")
    return _NORM_RE.sub(" ", joined).strip().lower()


def match_patterns(text: str, is_inflow: bool) -> list:
    """Все сработавшие паттерны, отсортированные по убыванию приоритета."""
    direction = "in" if is_inflow else "out"
    hits = []
    for pattern, rx in _COMPILED:
        if pattern.direction not in (direction, "any"):
            continue
        if rx.search(text):
            hits.append(pattern)
    hits.sort(key=lambda p: -p.priority)
    return hits


def best_pattern(text: str, is_inflow: bool):
    hits = match_patterns(text, is_inflow)
    return hits[0] if hits else None
